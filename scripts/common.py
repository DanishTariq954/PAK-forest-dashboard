"""
Shared helpers for the Pakistan Forest Watch pipeline.

Authentication:
  In GitHub Actions this reads the EE_SERVICE_ACCOUNT_KEY secret (the full
  JSON key file content, as a single string) and authenticates non-interactively.
  Locally (e.g. testing in Colab) it falls back to ee.Authenticate() if no
  service-account key is found in the environment.
"""

import json
import os
import ee


def init_earth_engine():
    """Initialize Earth Engine using a service account in CI, or interactive
    auth when running locally / in Colab."""
    key_data = os.environ.get("EE_SERVICE_ACCOUNT_KEY")

    if key_data:
        # Running in GitHub Actions (or anywhere the secret is injected)
        key_dict = json.loads(key_data)
        credentials = ee.ServiceAccountCredentials(
            key_dict["client_email"], key_data=key_data
        )
        ee.Initialize(credentials, project=key_dict["project_id"])
        print("Earth Engine initialized with service account:", key_dict["client_email"])
    else:
        # Local / Colab fallback
        project_id = os.environ.get("EE_PROJECT_ID", "trans-equator-468607-p0")
        ee.Authenticate()
        ee.Initialize(project=project_id)
        print("Earth Engine initialized interactively for project:", project_id)


